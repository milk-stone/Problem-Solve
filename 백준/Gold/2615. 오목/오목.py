dydx = [(1, 0), (1, 1), (0, 1), (-1, 1)]


def solve(sy, sx):
    sv = b[sy][sx]
    for dy, dx in dydx:
        y, x = sy, sx

        if 0 <= y - dy < 19 and 0 <= x - dx < 19 and b[y - dy][x - dx] == sv:
            continue

        i = 0
        draw = False
        while i < 4:
            y += dy
            x += dx
            if y < 0 or y >= 19 or x < 0 or x >= 19:
                draw = True
                break
            if b[y][x] != sv:
                draw = True
                break
            i += 1

        if not draw:
            y += dy
            x += dx
            if y < 0 or y >= 19 or x < 0 or x >= 19:
                return sv
            if b[y][x] != sv:
                return sv
    return 0


